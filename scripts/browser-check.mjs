import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1512, height: 982 }, deviceScaleFactor: 1 });
const errors = []; page.on('pageerror', e => errors.push(e.message));
await page.goto('http://127.0.0.1:4173');
await page.locator('.code-node').first().waitFor();
assert.equal(await page.locator('.code-node').count(), 10);
await page.screenshot({ path: '/tmp/code-atlas-desktop.png', fullPage: true });
await page.locator('.tree-function').filter({ hasText: 'step' }).first().click();
await page.locator('#inspector h2').waitFor();
assert.match(await page.locator('#inspector').innerText(), /Actor.forward/);
await page.getByRole('button', { name: 'Đóng chi tiết' }).click();
const node = page.locator('.code-node').first(); const before = await node.boundingBox();
await page.mouse.move(before.x + 70, before.y + 15); await page.mouse.down(); await page.mouse.move(before.x + 140, before.y + 65, { steps: 6 }); await page.mouse.up();
const after = await node.boundingBox(); assert.ok(Math.abs(after.x - before.x) > 30);
if (await page.getByRole('button', { name: 'Đóng chi tiết' }).isVisible()) await page.getByRole('button', { name: 'Đóng chi tiết' }).click();
assert.equal(await page.locator('.class-group').count(), 2);
assert.deepEqual(await page.locator('.class-heading > span:first-child').allInnerTexts(), ['class RobotController', 'class Actor']);
const frame = page.locator('.class-group').last(), frameBefore = await frame.boundingBox();
const frameHead = await page.locator('.class-heading').last().boundingBox();
await page.mouse.move(frameHead.x + 20, frameHead.y + frameHead.height / 2); await page.mouse.down(); await page.mouse.move(frameHead.x + 150, frameHead.y + 110, { steps: 8 }); await page.mouse.up();
const frameAfter = await frame.boundingBox();
assert.ok(frameAfter.x - frameBefore.x > 60 && frameAfter.y - frameBefore.y > 40, 'dragging a class heading should move its methods');
await page.locator('#arrange-button').click(); await page.waitForTimeout(300);
assert.equal(await page.locator('.class-group').count(), 2);
await page.screenshot({ path: '/tmp/code-atlas-classes.png', fullPage: true });
await page.locator('[data-sample="stm32"]').click();
await page.waitForFunction(() => document.querySelector('#project-title').textContent.includes('STM32'));
await page.locator('.tree-function').filter({ hasText: 'HAL_TIM_PeriodElapsedCallback' }).click();
assert.match(await page.locator('#inspector').innerText(), /HAL\/phần cứng/);
await page.screenshot({ path: '/tmp/code-atlas-stm32.png', fullPage: true });
await page.locator('#open-source').click();
await page.locator('#filename').fill('main.py');
await page.locator('#source-text').fill('def sensor():\n    return 1\n\ndef step():\n    return sensor()\n');
while (await page.locator('.source-tab').count() > 1) await page.locator('[data-remove-draft]').last().click();
await page.locator('#analyze-button').click();
await page.locator('#source-dialog').waitFor({ state: 'hidden' });
assert.equal(await page.locator('.code-node').count(), 2);
await page.locator('#search').fill('sensor'); assert.equal(await page.locator('.tree-function').count(), 2);
await page.locator('#search').fill('');
await page.getByRole('button', { name: 'Thêm ghi chú', exact: true }).click();
const area = await page.locator('#viewport').boundingBox(); await page.mouse.click(area.x + 80, area.y + 120);
await page.getByRole('textbox', { name: 'Nội dung ghi chú' }).fill('Observation trước policy');
await page.waitForTimeout(400); await page.reload(); await page.locator('.code-node').first().waitFor();
assert.equal(await page.locator('.code-node').count(), 2);
assert.equal(await page.getByRole('textbox', { name: 'Nội dung ghi chú' }).inputValue(), 'Observation trước policy');
const downloadPromise = page.waitForEvent('download'); await page.locator('#export-button').click(); const download = await downloadPromise; await download.saveAs('/tmp/code-atlas-test-export.json');
await page.locator('#open-source').click(); await page.locator('#file-input').setInputFiles('/tmp/code-atlas-test-export.json'); await page.locator('#source-dialog').waitFor({ state: 'hidden' });
await page.setViewportSize({ width: 390, height: 844 }); await page.screenshot({ path: '/tmp/code-atlas-mobile.png', fullPage: true });
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
await page.locator('#toggle-sidebar').click(); assert.equal(await page.locator('#sidebar').isVisible(), true);
await page.locator('[data-sample="locomotion"]').click();
await page.waitForFunction(() => document.querySelectorAll('.code-node').length === 10);
await page.setViewportSize({ width: 1512, height: 982 });
await page.waitForTimeout(300);
await page.locator('#open-source').click();
await page.locator('#filename').fill('base.py');
await page.locator('#source-text').fill('class BasePolicy:\n    def reset(self):\n        return 0\n\n    def forward(self, obs):\n        return obs\n');
while (await page.locator('.source-tab').count() > 1) await page.locator('[data-remove-draft]').last().click();
await page.locator('#new-file').click();
await page.locator('#filename').fill('walk.py');
await page.locator('#source-text').fill('import torch\nfrom base import BasePolicy\n\nclass WalkPolicy(BasePolicy):\n    @torch.no_grad()\n    def forward(self, obs):\n        super().forward(obs)\n        self.reset()\n        print(torch.zeros(3).abs().sum())\n        return obs\n');
await page.locator('#analyze-button').click();
await page.locator('#source-dialog').waitFor({ state: 'hidden' });
await page.waitForFunction(() => document.querySelectorAll('.code-node').length === 3);
assert.deepEqual(await page.locator('.class-heading > span:first-child').allInnerTexts(), ['class BasePolicy', 'class WalkPolicy(BasePolicy)']);
await page.locator('.tree-function').filter({ hasText: 'forward' }).last().click();
await page.locator('#inspector h2').waitFor();
const inherited = await page.locator('#inspector').innerText();
for (const pattern of [/KẾ THỪA: BasePolicy/, /@torch\.no_grad\(\)/, /kế thừa/, /BasePolicy\.forward/, /BasePolicy\.reset/]) assert.match(inherited, pattern);
for (const pattern of [/KHÔNG VẼ KẾT NỐI \(4\)/, /torch · 1/, /Python builtin · 1/, /chuỗi gọi trung gian · 2/]) assert.match(inherited, pattern);
assert.doesNotMatch(inherited, /CHƯA XÁC ĐỊNH/);
await page.screenshot({ path: '/tmp/code-atlas-inheritance.png', fullPage: true });
// a real package has several __init__.py; picking files gives basenames only, so they must be kept apart
const pkg = join(tmpdir(), `code-atlas-pkg-${process.pid}`);
for (const sub of ['a', 'b']) { mkdirSync(join(pkg, sub), { recursive: true }); writeFileSync(join(pkg, sub, '__init__.py'), `def ${sub}_entry():\n    return 1\n`); }
await page.locator('#open-source').click();
await page.locator('#file-input').setInputFiles([join(pkg, 'a', '__init__.py'), join(pkg, 'b', '__init__.py')]);
await page.waitForTimeout(500);
assert.match(await page.locator('#source-error').innerText(), /trùng tên đã được đổi tên/);
assert.deepEqual((await page.locator('.source-tab').allInnerTexts()).map(t => t.split('\n')[0]), ['__init__.py', '__init__~2.py']);
await page.locator('#analyze-button').click();
await page.locator('#source-dialog').waitFor({ state: 'hidden' });
await page.waitForFunction(() => document.querySelectorAll('.code-node').length === 2);
rmSync(pkg, { recursive: true, force: true });
assert.deepEqual(errors, []);
await browser.close();
console.log('Browser QA passed: examples, inspector, drag, input, notes, persistence, JSON export/import, mobile, class frames, inheritance.');
